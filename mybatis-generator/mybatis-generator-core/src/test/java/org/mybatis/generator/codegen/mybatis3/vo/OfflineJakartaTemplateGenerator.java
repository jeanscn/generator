package org.mybatis.generator.codegen.mybatis3.vo;

import com.github.javaparser.JavaParser;
import com.github.javaparser.ParserConfiguration;
import com.github.javaparser.ast.CompilationUnit;
import com.github.javaparser.ast.ImportDeclaration;
import com.github.javaparser.printer.lexicalpreservation.LexicalPreservingPrinter;
import org.mybatis.generator.api.dom.java.FullyQualifiedJavaType;
import org.mybatis.generator.api.dom.java.TopLevelClass;

import java.io.InputStream;
import java.io.OutputStream;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.security.MessageDigest;
import java.util.ArrayList;
import java.util.HexFormat;
import java.util.List;
import java.util.Map;
import java.util.Properties;

/**
 * Explicit migration bootstrap for authorized generated extension snapshots.
 * Only the two approved annotation imports are regenerated; no database/configuration execution.
 */
public final class OfflineJakartaTemplateGenerator {
    private static final String MARKER = "The content below is generated by vgosoft's code factory.";
    private static final Map<String, String> TYPES = Map.of(
            "javax.annotation.Resource", "jakarta.annotation.Resource",
            "javax.validation.constraints.AssertTrue", "jakarta.validation.constraints.AssertTrue");

    private OfflineJakartaTemplateGenerator() {
    }

    public static String generate(String source) {
        if (!source.contains(MARKER)) {
            throw new IllegalArgumentException("Missing protected generation marker");
        }
        JavaParser parser = new JavaParser(new ParserConfiguration()
                .setLanguageLevel(ParserConfiguration.LanguageLevel.JAVA_17));
        CompilationUnit unit = parser.parse(source).getResult()
                .orElseThrow(() -> new IllegalArgumentException("Cannot parse snapshot"));
        CompilationUnit before = unit.clone();
        LexicalPreservingPrinter.setup(unit);
        TopLevelClass typeOutput = new TopLevelClass("offline.AnnotationTypes");
        int changes = 0;
        for (ImportDeclaration declaration : unit.getImports()) {
            String name = declaration.getNameAsString();
            if (!TYPES.containsKey(name)) {
                continue;
            }
            if (declaration.isStatic() || declaration.isAsterisk()) {
                throw new IllegalArgumentException("Only explicit annotation type imports are supported");
            }
            FullyQualifiedJavaType generatedType = new FullyQualifiedJavaType(TYPES.get(name));
            typeOutput.addImportedType(generatedType);
            declaration.setName(generatedType.getFullyQualifiedName());
            changes++;
        }
        if (changes == 0) {
            throw new IllegalArgumentException("No approved annotation import found");
        }
        for (ImportDeclaration declaration : before.getImports()) {
            if (TYPES.containsKey(declaration.getNameAsString())) {
                declaration.setName(TYPES.get(declaration.getNameAsString()));
            }
        }
        if (!before.equals(unit)) {
            throw new IllegalStateException("Non-import AST contracts changed");
        }
        String output = LexicalPreservingPrinter.print(unit);
        if (!output.contains(MARKER)) {
            throw new IllegalStateException("Generation marker changed");
        }
        return output;
    }

    public static void main(String[] args) throws Exception {
        if (args.length == 2 && "apply".equals(args[0])) {
            apply(Path.of(args[1]));
        } else if (args.length == 5 && "stage".equals(args[0])) {
            stage(Path.of(args[1]), Path.of(args[2]), Path.of(args[3]), Path.of(args[4]));
        } else {
            throw new IllegalArgumentException("Usage: stage sourceRoot snapshotRoot stagingRoot manifest.properties | apply manifest.properties");
        }
    }

    private static void stage(Path sourceRoot, Path snapshotRoot, Path stagingRoot, Path manifest) throws Exception {
        sourceRoot = sourceRoot.toAbsolutePath().normalize();
        snapshotRoot = snapshotRoot.toAbsolutePath().normalize();
        stagingRoot = stagingRoot.toAbsolutePath().normalize();
        if (snapshotRoot.startsWith(sourceRoot) || stagingRoot.startsWith(sourceRoot)
                || snapshotRoot.startsWith(stagingRoot) || stagingRoot.startsWith(snapshotRoot)
                || Files.exists(manifest)) {
            throw new IllegalArgumentException("Use distinct output roots outside sourceRoot and a new manifest");
        }
        Properties records = new Properties();
        records.setProperty("sourceRoot", sourceRoot.toString());
        records.setProperty("snapshotRoot", snapshotRoot.toString());
        records.setProperty("stagingRoot", stagingRoot.toString());
        List<Path> candidates;
        Path candidateRoot = sourceRoot;
        try (var paths = Files.walk(sourceRoot)) {
            candidates = paths.filter(Files::isRegularFile)
                    .filter(p -> p.toString().endsWith(".java"))
                    .filter(p -> p.toString().contains("\\src\\main\\java\\"))
                    .filter(p -> !candidateRoot.relativize(p).toString().contains("\\target\\"))
                    .sorted().toList();
        }
        int count = 0;
        for (Path candidate : candidates) {
            String source = Files.readString(candidate, StandardCharsets.UTF_8);
            if (!source.contains(MARKER) || TYPES.keySet().stream().noneMatch(source::contains)) {
                continue;
            }
            Path relative = sourceRoot.relativize(candidate);
            Path snapshot = snapshotRoot.resolve(relative);
            Path output = stagingRoot.resolve(relative);
            if (Files.exists(snapshot) || Files.exists(output)) {
                throw new IllegalArgumentException("Refusing existing snapshot/output: " + relative);
            }
            String generated = generate(source);
            Files.createDirectories(snapshot.getParent());
            Files.createDirectories(output.getParent());
            Files.copy(candidate, snapshot);
            Files.writeString(output, generated, StandardCharsets.UTF_8);
            if (!hash(candidate).equals(hash(snapshot))) {
                throw new IllegalStateException("Concurrent snapshot change: " + relative);
            }
            records.setProperty(count + ".path", relative.toString());
            records.setProperty(count + ".sourceHash", hash(snapshot));
            records.setProperty(count + ".generatedHash", hash(output));
            System.out.println("STAGED " + relative);
            count++;
        }
        records.setProperty("count", Integer.toString(count));
        Files.createDirectories(manifest.toAbsolutePath().getParent());
        try (OutputStream stream = Files.newOutputStream(manifest)) {
            records.store(stream, "Authorized offline Jakarta generated-template run; SHA-256");
        }
        System.out.println("Staged protected templates: " + count);
    }

    private static void apply(Path manifest) throws Exception {
        Properties records = new Properties();
        try (InputStream stream = Files.newInputStream(manifest)) {
            records.load(stream);
        }
        Path sourceRoot = Path.of(records.getProperty("sourceRoot")).toAbsolutePath().normalize();
        Path snapshotRoot = Path.of(records.getProperty("snapshotRoot")).toAbsolutePath().normalize();
        Path stagingRoot = Path.of(records.getProperty("stagingRoot")).toAbsolutePath().normalize();
        int count = Integer.parseInt(records.getProperty("count"));
        List<Path[]> approved = new ArrayList<>();
        for (int i = 0; i < count; i++) {
            Path relative = Path.of(records.getProperty(i + ".path"));
            if (relative.isAbsolute() || relative.normalize().startsWith("..")) {
                throw new IllegalArgumentException("Invalid manifest path");
            }
            Path source = sourceRoot.resolve(relative);
            Path snapshot = snapshotRoot.resolve(relative);
            Path generated = stagingRoot.resolve(relative);
            if (!hash(source).equals(records.getProperty(i + ".sourceHash"))
                    || !hash(snapshot).equals(records.getProperty(i + ".sourceHash"))
                    || !hash(generated).equals(records.getProperty(i + ".generatedHash"))
                    || !generate(Files.readString(snapshot, StandardCharsets.UTF_8))
                    .equals(Files.readString(generated, StandardCharsets.UTF_8))) {
                throw new IllegalStateException("Changed source/snapshot/output; refusing application: " + relative);
            }
            approved.add(new Path[]{source, snapshot, generated});
        }
        for (Path[] paths : approved) {
            if (!hash(paths[0]).equals(hash(paths[1]))) {
                throw new IllegalStateException("Concurrent business change: " + paths[0]);
            }
            Files.copy(paths[2], paths[0], java.nio.file.StandardCopyOption.REPLACE_EXISTING);
            if (!hash(paths[0]).equals(hash(paths[2]))) {
                throw new IllegalStateException("Application verification failed: " + paths[0]);
            }
            System.out.println("APPLIED " + sourceRoot.relativize(paths[0]));
        }
        System.out.println("Applied protected templates: " + count);
    }

    private static String hash(Path path) throws Exception {
        return HexFormat.of().formatHex(MessageDigest.getInstance("SHA-256").digest(Files.readAllBytes(path)));
    }
}

package org.mybatis.generator.codegen.mybatis3.vo;

import com.github.javaparser.JavaParser;
import com.github.javaparser.ParserConfiguration;
import com.github.javaparser.ast.CompilationUnit;
import com.github.javaparser.ast.ImportDeclaration;
import com.github.javaparser.ast.body.FieldDeclaration;
import com.github.javaparser.ast.expr.AnnotationExpr;
import com.github.javaparser.ast.expr.NormalAnnotationExpr;
import com.github.javaparser.printer.lexicalpreservation.LexicalPreservingPrinter;
import org.mybatis.generator.api.IntrospectedColumn;
import org.mybatis.generator.api.dom.java.Field;
import org.mybatis.generator.api.dom.java.FullyQualifiedJavaType;
import org.mybatis.generator.api.dom.java.TopLevelClass;
import org.mybatis.generator.plugins.FieldJsonFormatPlugin;
import org.w3c.dom.Element;
import org.w3c.dom.NodeList;

import javax.xml.XMLConstants;
import javax.xml.parsers.DocumentBuilderFactory;
import java.io.StringReader;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.LinkedHashMap;
import java.util.Locale;
import java.util.Map;
import java.util.regex.Matcher;
import java.util.regex.Pattern;
import org.xml.sax.InputSource;

/**
 * Offline test/bootstrap utility regenerating configured JSON serialization on a VO extension template.
 * Schema SQL is parsed as text, never executed; all other template contracts remain untouched.
 */
public final class OfflineJsonVoGenerator {
    private static final String MARKER = "The content below is generated by vgosoft's code factory.";
    private static final String OLD_IMPORT = "com.fasterxml.jackson.databind.annotation.JsonSerialize";
    private static final String NEW_IMPORT = "tools.jackson.databind.annotation.JsonSerialize";
    private static final Pattern TABLE = Pattern.compile(
            "(?im)^\\s*CREATE TABLE IF NOT EXISTS\\s+([a-zA-Z0-9_]+)\\s*\\(");
    private static final Pattern COLUMN = Pattern.compile(
            "(?im)^\\s*([a-zA-Z0-9_]+)\\s+(VARCHAR|TEXT|LONGTEXT|MEDIUMTEXT|INT|TIMESTAMP|JSON)\\b");

    private OfflineJsonVoGenerator() {
    }

    public static void main(String[] args) throws Exception {
        if (args.length != 4) {
            throw new IllegalArgumentException("Usage: OfflineJsonVoGenerator config.xml schema.sql template.java staging.java");
        }
        Path template = Path.of(args[2]).toAbsolutePath().normalize();
        Path output = Path.of(args[3]).toAbsolutePath().normalize();
        if (template.equals(output) || (Files.exists(output) && Files.isSameFile(template, output))) {
            throw new IllegalArgumentException("Output must be a separate staging file, not the business template");
        }
        String generated = generate(Files.readString(Path.of(args[0]), StandardCharsets.UTF_8),
                Files.readString(Path.of(args[1]), StandardCharsets.UTF_8),
                Files.readString(template, StandardCharsets.UTF_8));
        Files.createDirectories(output.getParent());
        Files.writeString(output, generated, StandardCharsets.UTF_8);
        System.out.println("Offline JSON VO generated: " + output);
    }

    public static String generate(String configXml, String schemaSql, String templateSource) throws Exception {
        if (!templateSource.contains(MARKER)) {
            throw new IllegalArgumentException("The extension template must carry the generated-code marker");
        }
        Matcher tableMatcher = TABLE.matcher(schemaSql);
        if (!tableMatcher.find()) {
            throw new IllegalArgumentException("Unsupported offline schema: expected a CREATE TABLE IF NOT EXISTS");
        }
        String tableName = tableMatcher.group(1);
        if (tableMatcher.find()) {
            throw new IllegalArgumentException("Only one table is permitted per offline schema");
        }
        Map<String, String> physicalTypes = new LinkedHashMap<>();
        Matcher columns = COLUMN.matcher(schemaSql);
        while (columns.find()) {
            String name = columns.group(1).toLowerCase(Locale.ROOT);
            if (physicalTypes.put(name, columns.group(2).toUpperCase(Locale.ROOT)) != null) {
                throw new IllegalArgumentException("Duplicate schema column: " + name);
            }
        }
        Map<String, String> logicalTypes = logicalTypes(configXml, tableName);
        if (logicalTypes.isEmpty()) {
            throw new IllegalArgumentException("No columnOverride/property logicalType configured for " + tableName);
        }
        JavaParser parser = new JavaParser(new ParserConfiguration()
                .setLanguageLevel(ParserConfiguration.LanguageLevel.JAVA_17));
        CompilationUnit unit = parser.parse(templateSource).getResult()
                .orElseThrow(() -> new IllegalArgumentException("Cannot parse VO extension template"));
        CompilationUnit original = unit.clone();
        LexicalPreservingPrinter.setup(unit);
        FieldJsonFormatPlugin plugin = new FieldJsonFormatPlugin();
        Map<String, Boolean> consumed = new LinkedHashMap<>();
        for (FieldDeclaration declaration : unit.findAll(FieldDeclaration.class)) {
            if (declaration.isStatic()) {
                continue;
            }
            NormalAnnotationExpr meta = declaration.getAnnotationByName("ColumnMeta")
                    .filter(AnnotationExpr::isNormalAnnotationExpr)
                    .map(AnnotationExpr::asNormalAnnotationExpr)
                    .orElseThrow(() -> new IllegalArgumentException("Missing ColumnMeta on " + declaration.getVariables()));
            String columnName = meta.getPairs().stream().filter(p -> p.getNameAsString().equals("value"))
                    .map(p -> p.getValue().asStringLiteralExpr().asString().toLowerCase(Locale.ROOT))
                    .findFirst().orElseThrow(() -> new IllegalArgumentException("Missing ColumnMeta.value"));
            if (!physicalTypes.containsKey(columnName)) {
                throw new IllegalArgumentException("Template column absent from schema: " + columnName);
            }
            if (!logicalTypes.containsKey(columnName)) {
                continue;
            }
            if (declaration.getVariables().size() != 1
                    || !declaration.getVariable(0).getType().asString().equals("String")) {
                throw new IllegalArgumentException("Logical JSON template field must be one String: " + columnName);
            }
            String physicalType = physicalTypes.get(columnName);
            if (!physicalType.matches("TEXT|LONGTEXT|MEDIUMTEXT|VARCHAR|JSON")) {
                throw new IllegalArgumentException("Logical JSON requires a text-compatible schema column: " + columnName);
            }
            AnnotationExpr previous = declaration.getAnnotationByName("JsonSerialize")
                    .orElseThrow(() -> new IllegalArgumentException("Template JSON contract missing: " + columnName));
            if (!previous.toString().replaceAll("\\s", "").equals("@JsonSerialize(using=JsonRecordSerializer.class)")) {
                throw new IllegalArgumentException("Custom JSON serializer must not be overwritten: " + columnName);
            }
            IntrospectedColumn column = new IntrospectedColumn();
            column.setActualColumnName(columnName);
            column.setActualTypeName(physicalType);
            column.setFullyQualifiedJavaType(FullyQualifiedJavaType.getStringInstance());
            column.getProperties().setProperty(FieldJsonFormatPlugin.LOGICAL_TYPE_PROPERTY, logicalTypes.get(columnName));
            Field field = new Field(declaration.getVariable(0).getNameAsString(), FullyQualifiedJavaType.getStringInstance());
            TopLevelClass generated = new TopLevelClass("offline.JsonVo");
            plugin.voAbstractFieldGenerated(field, generated, column, null);
            if (!generated.getImportedTypes().contains(new FullyQualifiedJavaType(NEW_IMPORT))
                    || field.getAnnotations().size() != 1) {
                throw new IllegalStateException("JSON serialization plugin did not produce the expected contract");
            }
            AnnotationExpr annotation = parser.parseAnnotation(field.getAnnotations().get(0)).getResult().orElseThrow();
            previous.replace(annotation);
            if (consumed.put(columnName, true) != null) {
                throw new IllegalArgumentException("Duplicate template column: " + columnName);
            }
        }
        if (!consumed.keySet().equals(logicalTypes.keySet())) {
            throw new IllegalArgumentException("Configured logical JSON columns do not match the template: " + logicalTypes.keySet());
        }
        ImportDeclaration serializerImport = unit.getImports().stream()
                .filter(i -> !i.isStatic() && !i.isAsterisk()
                        && (i.getNameAsString().equals(OLD_IMPORT) || i.getNameAsString().equals(NEW_IMPORT)))
                .findFirst().orElseThrow(() -> new IllegalArgumentException("Missing explicit JsonSerialize import"));
        serializerImport.setName(NEW_IMPORT);
        if (!withoutSerializerContracts(original).equals(withoutSerializerContracts(unit.clone()))) {
            throw new IllegalStateException("Generation changed non-serializer template contracts");
        }
        return LexicalPreservingPrinter.print(unit);
    }

    private static String withoutSerializerContracts(CompilationUnit unit) {
        unit.getImports().removeIf(i -> i.getNameAsString().equals(OLD_IMPORT) || i.getNameAsString().equals(NEW_IMPORT));
        unit.findAll(FieldDeclaration.class).forEach(f -> f.getAnnotations()
                .removeIf(a -> a.getNameAsString().equals("JsonSerialize")));
        return unit.toString();
    }

    private static Map<String, String> logicalTypes(String configXml, String tableName) throws Exception {
        // The business configuration may contain JDBC credentials and output destinations.
        // Read only column-level properties; neither configuration execution nor entity resolution is permitted.
        DocumentBuilderFactory factory = DocumentBuilderFactory.newInstance();
        factory.setFeature(XMLConstants.FEATURE_SECURE_PROCESSING, true);
        factory.setFeature("http://xml.org/sax/features/external-general-entities", false);
        factory.setFeature("http://xml.org/sax/features/external-parameter-entities", false);
        factory.setFeature("http://apache.org/xml/features/nonvalidating/load-external-dtd", false);
        factory.setAttribute(XMLConstants.ACCESS_EXTERNAL_DTD, "");
        factory.setAttribute(XMLConstants.ACCESS_EXTERNAL_SCHEMA, "");
        factory.setXIncludeAware(false);
        factory.setExpandEntityReferences(false);
        NodeList tables = factory.newDocumentBuilder().parse(new InputSource(new StringReader(configXml)))
                .getElementsByTagName("table");
        Map<String, String> result = new LinkedHashMap<>();
        int matches = 0;
        for (int i = 0; i < tables.getLength(); i++) {
            Element table = (Element) tables.item(i);
            if (!tableName.equals(table.getAttribute("tableName"))) {
                continue;
            }
            matches++;
            NodeList overrides = table.getElementsByTagName("columnOverride");
            for (int j = 0; j < overrides.getLength(); j++) {
                Element override = (Element) overrides.item(j);
                NodeList properties = override.getElementsByTagName("property");
                for (int k = 0; k < properties.getLength(); k++) {
                    Element property = (Element) properties.item(k);
                    if (FieldJsonFormatPlugin.LOGICAL_TYPE_PROPERTY.equals(property.getAttribute("name"))) {
                        String column = override.getAttribute("column").toLowerCase(Locale.ROOT);
                        if (result.put(column, property.getAttribute("value")) != null) {
                            throw new IllegalArgumentException("Duplicate logicalType property: " + column);
                        }
                    }
                }
            }
        }
        if (matches != 1) {
            throw new IllegalArgumentException("Expected exactly one configured table: " + tableName);
        }
        return result;
    }
}

package org.mybatis.generator.codegen.mybatis3.vo;

import org.junit.jupiter.api.Test;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

class OfflineJsonVoGeneratorTest {
    private static final String CONFIG = """
            <!DOCTYPE generatorConfiguration SYSTEM "file:///nonexistent/offline.dtd">
            <generatorConfiguration><context>
              <jdbcConnection connectionURL="jdbc:invalid:must-not-connect"/>
              <table tableName="records">
                <columnOverride column="json_record"><property name="logicalType" value="JSON"/></columnOverride>
              </table>
            </context></generatorConfiguration>
            """;
    private static final String SCHEMA = """
            CREATE TABLE IF NOT EXISTS records (
                name_ VARCHAR(255) NULL COMMENT '名称',
                json_record TEXT NULL COMMENT 'JSON内容'
            );
            """;
    private static final String TEMPLATE = """
            /*
             * The content below is generated by vgosoft's code factory.
             */
            package example;
            import com.fasterxml.jackson.databind.annotation.JsonSerialize;
            import com.vgosoft.system.parser.JsonRecordSerializer;
            public abstract class RecordVo {
                @ColumnMeta(value = "name_", order = 12)
                @Size(max = 255)
                protected String name;
                @ColumnMeta(value = "json_record", size = 1073741824, type = JDBCType.LONGVARCHAR)
                @JsonSerialize(using = JsonRecordSerializer.class)
                @VueFormItemMeta(component = "editor")
                protected String jsonRecord;
                public String customExtension() { return name; }
            }
            """;

    @Test
    void shouldRegenerateFromTextSchemaAndExtensionTemplateWithoutDatabaseOrDtd() throws Exception {
        String output = OfflineJsonVoGenerator.generate(CONFIG, SCHEMA, TEMPLATE);
        assertThat(output).isEqualTo(TEMPLATE.replace("com.fasterxml.jackson.databind.annotation.JsonSerialize",
                "tools.jackson.databind.annotation.JsonSerialize"));
        assertThat(OfflineJsonVoGenerator.generate(CONFIG, SCHEMA, output)).isEqualTo(output);
    }

    @Test
    void shouldRefuseUnknownLogicalType() {
        assertThatThrownBy(() -> OfflineJsonVoGenerator.generate(CONFIG.replace("JSON", "JSNO"), SCHEMA, TEMPLATE))
                .isInstanceOf(IllegalArgumentException.class).hasMessageContaining("Unsupported logicalType");
    }

    @Test
    void shouldRefuseMissingSchemaColumnOrUnmatchedTemplate() {
        assertThatThrownBy(() -> OfflineJsonVoGenerator.generate(CONFIG, SCHEMA.replace("json_record TEXT", "other TEXT"), TEMPLATE))
                .isInstanceOf(IllegalArgumentException.class).hasMessageContaining("absent from schema");
        assertThatThrownBy(() -> OfflineJsonVoGenerator.generate(CONFIG.replace("column=\"json_record\"", "column=\"absent\""), SCHEMA, TEMPLATE))
                .isInstanceOf(IllegalArgumentException.class).hasMessageContaining("do not match");
    }

    @Test
    void shouldRefuseOverwritingCustomSerializerOrRemovingMarker() {
        assertThatThrownBy(() -> OfflineJsonVoGenerator.generate(CONFIG, SCHEMA, TEMPLATE.replace("JsonRecordSerializer.class", "CustomSerializer.class")))
                .isInstanceOf(IllegalArgumentException.class).hasMessageContaining("must not be overwritten");
        assertThatThrownBy(() -> OfflineJsonVoGenerator.generate(CONFIG, SCHEMA,
                TEMPLATE.replace("The content below is generated by vgosoft's code factory.", "")))
                .isInstanceOf(IllegalArgumentException.class).hasMessageContaining("marker");
    }

    @Test
    void shouldRefuseMissingLogicalTypeOrWrongPhysicalType() {
        assertThatThrownBy(() -> OfflineJsonVoGenerator.generate(CONFIG.replace("logicalType", "other"), SCHEMA, TEMPLATE))
                .isInstanceOf(IllegalArgumentException.class).hasMessageContaining("No columnOverride");
        assertThatThrownBy(() -> OfflineJsonVoGenerator.generate(CONFIG, SCHEMA.replace("json_record TEXT", "json_record INT"), TEMPLATE))
                .isInstanceOf(IllegalArgumentException.class).hasMessageContaining("text-compatible");
    }
}
